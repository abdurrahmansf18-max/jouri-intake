export function apiError(err: unknown, locale: Locale): string {
  const t = COPY[locale];
  if (err instanceof Error) {
    const code = err.message;
    if (t.errors[code]) return t.errors[code];
  }
  return t.errors.ERR_GENERAL;
}

// Arapça hareke + elif/ya normalizasyonu + Almanca/Latin aksan kaldırma
export function normalizeText(str: string): string {
  return str
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")       // Latin aksan işaretleri (ä→a, ö→o, ü→u)
    .replace(/[ً-ٰٟ]/g, "") // Arapça hareke (تشكيل)
    .replace(/[أإآٱ]/g, "ا")
    .replace(/[ىئ]/g, "ي")
    .replace(/ة/g, "ه")
    .toLocaleLowerCase();
}

export function searchTokens(query: string): string[] {
  return normalizeText(query).split(/\s+/).filter(Boolean);
}

export function logActionLabel(action: string, locale: Locale, details?: Record<string, unknown> | null): string {
  const t = COPY[locale];
  switch (action) {
    case "login": {
      const user = typeof details?.user === "string" ? details.user : "";
      return t.logLogin(user);
    }
    case "create": return details?.source === "bulk" ? t.logBulkCreate : t.logCreate;
    case "update": return t.logUpdate;
    case "delete": return t.logDelete;
    case "sell": {
      const qty = typeof details?.quantity === "number" ? details.quantity : 1;
      return t.logSell(qty);
    }
    case "restore": return t.logRestore;
    case "status_change": return t.logStatusChange;
    case "add_images": {
      const count = typeof details?.count === "number" ? details.count : 1;
      return t.logAddImages(count);
    }
    case "ai_generate_images": {
      const count = typeof details?.count === "number" ? details.count : 1;
      return t.logAiGenerateImages(count);
    }
    case "mark_ai_image": return (t as any).logMarkAiImage || "AI Marked";
    case "shopify_push": return t.logShopifyPush;
    case "reset_sales": return t.logResetSales;
    default: return t.logUnknown;
  }
}

